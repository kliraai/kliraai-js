/**
 * Evaluation runner for Klira AI SDK
 *
 * Provides evaluation capabilities for testing AI applications with
 * standard LLM metrics and Klira's unique compliance-focused metrics.
 */

import { KliraAI } from '../index.js';
import { loadDataset } from './dataset-loader.js';
import type {
  EvaluateOptions,
  KliraEvalResult,
  TestCaseResult,
} from './types.js';

/**
 * Evaluate an AI system with test cases
 *
 * This function runs your target function against a dataset of test cases,
 * captures traces for each execution, and generates evaluation results.
 *
 * **Trace-Based Evaluation Model:**
 * The SDK uses a platform-side trace-based evaluation model. This function:
 * 1. Loads test cases from the dataset
 * 2. Executes the target function for each test case
 * 3. Captures execution traces automatically via OTLP
 * 4. Returns basic test results and metadata
 *
 * Detailed evaluation metrics (pass rate, compliance reports, etc.) are
 * generated by the platform from captured traces.
 *
 * **How to Access Full Results:**
 * - Klira Dashboard: https://dashboard.getklira.com
 * - Platform API: GET /api/v1/eval-runs/{evalsRun}
 *
 * @param options - Evaluation options
 * @returns Evaluation result with test case outputs and metadata
 *
 * @example
 * ```typescript
 * import { evaluate } from '@kliraai/sdk';
 *
 * const result = await evaluate({
 *   target: async (input) => {
 *     // Your AI system logic here
 *     const response = await myAI.chat(input);
 *     return response.text;
 *   },
 *   data: 'tests/dataset.csv',
 *   evalsRun: 'eval_123',
 *   organizationId: 'org_456',
 *   projectId: 'proj_789',
 * });
 *
 * console.log(`Executed ${result.totalTestCases} test cases`);
 * console.log(`Duration: ${result.durationSeconds}s`);
 * console.log(`View results: ${result.hubUrl}`);
 * ```
 */
export async function evaluate(
  options: EvaluateOptions
): Promise<KliraEvalResult> {
  const startTime = Date.now();

  // Validate options
  if (!options.target) {
    throw new Error('target function is required');
  }
  if (!options.data) {
    throw new Error('data is required');
  }

  // Load dataset
  const testCases = await loadDataset(options.data);

  if (testCases.length === 0) {
    throw new Error('No test cases found in dataset');
  }

  // Configure eval run in SDK if provided
  if (options.evalsRun) {
    const config = KliraAI.getConfig();
    config.evalsRun = options.evalsRun;

    // Set organization and project context
    if (options.organizationId || options.projectId) {
      KliraAI.setHierarchyContext({
        organizationId: options.organizationId,
        projectId: options.projectId,
      });
    }
  }

  // Execute test cases
  const results: TestCaseResult[] = [];
  let passedCount = 0;
  let failedCount = 0;

  for (const testCase of testCases) {
    const caseStartTime = Date.now();
    let actualOutput = '';
    let error: string | undefined;
    let passed = false;

    try {
      // Set test case context for tracing
      if (KliraAI.getTracing()) {
        KliraAI.setTraceMetadata({
          requestId: testCase.id,
          metadata: testCase.metadata,
        });
      }

      // Execute target function
      actualOutput = await options.target(testCase.input);

      // Simple pass/fail based on expected output (if provided)
      if (testCase.expectedOutput !== undefined) {
        passed = actualOutput === testCase.expectedOutput;
      } else {
        // If no expected output, consider it passed if no error
        passed = true;
      }

      if (passed) {
        passedCount++;
      } else {
        failedCount++;
      }
    } catch (err) {
      error = err instanceof Error ? err.message : String(err);
      failedCount++;
    }

    const caseEndTime = Date.now();

    results.push({
      testCaseId: testCase.id || `test_${results.length}`,
      input: testCase.input,
      expectedOutput: testCase.expectedOutput,
      actualOutput,
      guardrailDecision: {}, // Populated by platform analysis
      metricScores: {}, // Populated by platform analysis
      passed,
      latencyMs: caseEndTime - caseStartTime,
      error,
    });
  }

  const endTime = Date.now();
  const durationSeconds = (endTime - startTime) / 1000;

  // Flush traces to ensure all eval data is sent
  await KliraAI.flush();

  // Construct result
  const result: KliraEvalResult = {
    totalTestCases: testCases.length,
    datasetPath: typeof options.data === 'string' ? options.data : undefined,
    testCases: results,
    evalsRun: options.evalsRun,
    createdAt: new Date(startTime),
    durationSeconds,

    // Legacy fields for backward compatibility
    passRate: passedCount / testCases.length,
    passedTestCases: passedCount,
    failedTestCases: failedCount,
    avgScores: {},
    metricResults: {},

    // Metadata
    experimentId: options.experimentId,
    organizationId: options.organizationId,
    projectId: options.projectId,
  };

  // Upload to hub if requested
  if (options.uploadToHub) {
    const hubUrl = await uploadToHub(result, {
      apiKey: options.hubApiKey,
      endpoint: options.hubEndpoint,
    });
    result.hubUrl = hubUrl;
  }

  return result;
}

/**
 * Upload evaluation results to Klira Hub
 */
async function uploadToHub(
  result: KliraEvalResult,
  options: { apiKey?: string; endpoint?: string }
): Promise<string> {
  const endpoint =
    options.endpoint || 'https://api.getklira.com/v1/eval-results';
  const apiKey = options.apiKey || KliraAI.getConfig().apiKey;

  if (!apiKey) {
    throw new Error(
      'API key required for hub upload. Set KLIRA_API_KEY or pass hubApiKey option.'
    );
  }

  try {
    const response = await fetch(endpoint, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        evalsRun: result.evalsRun,
        totalTestCases: result.totalTestCases,
        passRate: result.passRate,
        durationSeconds: result.durationSeconds,
        createdAt: result.createdAt,
        experimentId: result.experimentId,
        organizationId: result.organizationId,
        projectId: result.projectId,
        testCases: result.testCases?.map((tc) => ({
          id: tc.testCaseId,
          input: tc.input,
          output: tc.actualOutput,
          passed: tc.passed,
          latencyMs: tc.latencyMs,
          error: tc.error,
        })),
      }),
    });

    if (!response.ok) {
      throw new Error(`Hub upload failed: ${response.statusText}`);
    }

    const data = await response.json();
    return data.url || `https://dashboard.getklira.com/evals/${result.evalsRun}`;
  } catch (error) {
    console.error('Failed to upload to hub:', error);
    throw error;
  }
}
