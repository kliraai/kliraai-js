/**
 * Type definitions for Klira evaluation system
 *
 * Matches Python SDK evaluation types for cross-SDK compatibility
 */

/**
 * Compliance report with guardrail-specific metrics
 */
export interface ComplianceReport {
  // Overall metrics
  guardrailRecall: number; // % of violations correctly caught
  guardrailPrecision: number; // % of blocks that were justified
  policyCoverageRate?: number; // % of policies tested
  avgConfidence: number; // Average confidence across decisions

  // Policy-level breakdown
  policyMetrics: Record<string, Record<string, number>>; // policy_id -> {recall, precision, ...}
  untestedPolicies: string[]; // Policies with < min_trigger_count

  // Layer analysis
  layerDistribution: Record<string, Record<string, any>>; // layer -> {count, percentage}
  lowConfidenceCount: number;
  llmFallbackRate: number;

  // Fuzzy matching
  fuzzyMatchRecall?: number;
  fuzzyCaughtCount?: number;
  fuzzyMissedCount?: number;

  // Recommendations
  recommendations: string[];
}

/**
 * Individual test case result
 */
export interface TestCaseResult {
  testCaseId: string;
  input: string;
  expectedOutput?: string;
  actualOutput: string;

  // Guardrails decision
  guardrailDecision: Record<string, any>;

  // Metric scores
  metricScores: Record<string, number>;
  passed: boolean;

  // Metadata
  latencyMs: number;
  error?: string;
}

/**
 * Main evaluation result with trace-based model support
 *
 * The SDK uses a platform-side trace-based evaluation model.
 * This result object contains basic metadata and test cases with their outputs.
 * Detailed evaluation metrics are generated by the platform from captured traces.
 */
export interface KliraEvalResult {
  // Test case data (trace-based model)
  totalTestCases: number; // Total number of test cases executed
  datasetPath?: string; // Path to dataset file
  testCases?: TestCaseResult[]; // List of test cases with actual_output
  evalsRun?: string; // Eval run ID from config
  createdAt?: Date; // Timestamp of evaluation
  durationSeconds?: number; // Total execution time

  // Legacy fields (backward compatibility) - DEPRECATED
  // These fields are kept for backward compatibility but are no longer
  // populated in the new trace-based model
  passRate: number; // DEPRECATED: No longer computed
  passedTestCases: number; // DEPRECATED: Use platform API
  failedTestCases: number; // DEPRECATED: Use platform API
  avgScores: Record<string, number>; // DEPRECATED
  metricResults: Record<string, any[]>; // DEPRECATED
  complianceReport?: ComplianceReport; // DEPRECATED: Platform generates

  // Metadata (optional)
  experimentId?: string;
  organizationId?: string;
  projectId?: string;

  // Hub integration (optional)
  hubUrl?: string;
  hubEvalRunId?: string;

  // Raw results (optional)
  rawResults?: any;
}

/**
 * Options for evaluate() function
 */
export interface EvaluateOptions {
  // Target function to evaluate (async function that takes input and returns output)
  target: (input: string) => Promise<string>;

  // Dataset (array of test cases or path to CSV/JSON file)
  data: string | TestCase[];

  // Eval run ID (for grouping evaluations)
  evalsRun?: string;

  // Organization and project IDs for tracing
  organizationId?: string;
  projectId?: string;

  // Experiment ID for tracking
  experimentId?: string;

  // Evaluators (metric functions) - optional
  evaluators?: Evaluator[];

  // Upload results to hub
  uploadToHub?: boolean;

  // Hub configuration
  hubApiKey?: string;
  hubEndpoint?: string;
}

/**
 * Test case structure
 */
export interface TestCase {
  id?: string;
  input: string;
  expectedOutput?: string;
  metadata?: Record<string, any>;
}

/**
 * Evaluator function interface
 */
export interface Evaluator {
  name: string;
  evaluate: (testCase: TestCaseResult) => Promise<number>;
  description?: string;
}

/**
 * Dataset loader options
 */
export interface DatasetLoaderOptions {
  format?: 'csv' | 'json' | 'auto';
  inputColumn?: string;
  expectedOutputColumn?: string;
}
